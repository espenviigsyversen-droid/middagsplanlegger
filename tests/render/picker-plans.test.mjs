import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { renderPickerPlansView } from "../../src/render/picker-plans.js";
import { pencilIcon } from "../../src/render/icons.js";
const e = value => String(value ?? "").replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
const closed = renderPickerPlansView();
assert.match(closed, /picker-plan-option picker-other-plan/);
assert.match(closed, /<strong>Annen plan<\/strong>/);
assert.match(closed, /Spise borte, rester eller eget notat/);
assert.doesNotMatch(closed, /data-picker-note-input/);
const expanded = renderPickerPlansView({expanded:true,plans:[['away',{label:'Spise borte'}],['leftovers',{label:'Rester'}]]});
assert.match(expanded, />ANNEN PLAN</);assert.ok(expanded.includes(pencilIcon()));
assert.ok(expanded.indexOf('data-picker-plan="leftovers"') < expanded.indexOf('data-picker-own-note'));
assert.ok(expanded.indexOf('data-picker-own-note') < expanded.indexOf('data-picker-plans-cancel'));
const empty = renderPickerPlansView({noteDraft:{text:'  '}});
assert.match(empty,/Hva skjer denne dagen/);assert.match(empty,/maxlength="60"/);
assert.match(empty,/data-picker-note-save disabled/);assert.match(empty,/data-scroll-key="picker-note"/);
const filled = renderPickerPlansView({noteDraft:{text:'Cup <test>'},escapeHtml:e});
assert.match(filled,/value="Cup &lt;test>/);assert.doesNotMatch(filled,/data-picker-note-save disabled/);
assert.match(filled,/type="submit"[^>]*>Legg inn/);assert.match(filled,/data-picker-note-back>Tilbake/);
assert.match(renderPickerPlansView({noteDraft:{text:'x'.repeat(70)}}),new RegExp('value="'+'x'.repeat(60)+'"'));
const css=readFileSync(new URL('../../styles.css',import.meta.url),'utf8');
assert.match(css,/\.picker-other-plan \{ min-height: 56px/);
assert.match(css,/\.picker-footer \{[^}]*box-shadow: 0 -6px 16px rgba\(0,0,0,\.06\)/);
assert.match(css,/\.picker-note-form \.input \{[^}]*font-size: 16px/);
assert.match(css,/\.picker-note-form \.button:disabled \{ background: var\(--line\); color: var\(--muted\)/);
assert.equal(readFileSync(new URL('../../service-worker.js',import.meta.url),'utf8').split('src/render/picker-plans.js').length,3);
console.log('picker plans render tests ok');
