import assert from "node:assert/strict";
import { canonicalView, isoWeekNumber, weekHeading, weekSwipeDirection, weekEligibleDays, lastPlannedLabel } from "../../src/domain/week-view.js";
import { getWeekDatesForOffset } from "../../src/domain/weeks.js";
const base = new Date(2026,9,14,12), dates = offset => getWeekDatesForOffset(offset,base);
for (const [offset,title] of [[0,"Denne uken"],[1,"Neste uke"],[-1,"Forrige uke"],[2,"Uke 44"]]) assert.equal(weekHeading(dates(offset),offset).title,title);
assert.equal(weekHeading(dates(0),0).subtitle,"Uke 42 · 12.–18. okt.");
assert.equal(weekHeading(dates(2),2).subtitle,"Uke 44 · 26. okt.–1. nov.");
const year = getWeekDatesForOffset(0,new Date(2026,11,28,12));
assert.equal(isoWeekNumber(year[0]),53); assert.equal(isoWeekNumber(year[6]),53);
assert.equal(weekHeading(year,10).subtitle,"Uke 53 · 28. des.–3. jan.");
assert.equal(isoWeekNumber(new Date(2027,0,4)),1);
assert.equal(canonicalView("calendar"),"week");assert.equal(canonicalView("planner"),"week");assert.equal(canonicalView("shopping"),"shopping");
assert.deepEqual(weekEligibleDays({}, {1:true},{0:"home",1:"home",2:"away"},mode=>mode==="home"),[0]);
for(const [start,end,expected] of [[{x:100,y:40},{x:20,y:45},1],[{x:100,y:40},{x:180,y:45},-1],[{x:100,y:40},{x:100,y:140},0],[{x:10,y:40},{x:100,y:40},0],[{x:360,y:40},{x:200,y:40},0],[{x:100,y:40},{x:150,y:40},0],[{x:100,y:40},{x:170,y:110},0]]) assert.equal(weekSwipeDirection(start,end,375),expected);
assert.equal(lastPlannedLabel({"2026-09-14":{0:"a"}},"a",base),"Sist i planen for 4 uker siden");
assert.equal(lastPlannedLabel({"2026-10-05":{1:"a"}},"a",base),"Sist i planen forrige uke");
assert.equal(lastPlannedLabel({"2026-10-12":{0:"a",5:"a"}},"a",base),"");
assert.equal(lastPlannedLabel({"2026-10-19":{0:"a"}},"a",base),"");
console.log("week view domain tests ok");
